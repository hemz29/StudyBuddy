// Opens the phone upload page on a phone-sized screen, adds a photo and sends it.
import { chromium } from "playwright-core";
const S = process.env.S ?? ".", base = process.env.BASE ?? "http://localhost:3100";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const desk = await browser.newPage();
await desk.goto(base + "/profiles");
await desk.locator("form button").first().click();
await desk.waitForURL("**/learn");
await desk.goto(base + "/learn/worksheet/panchatantra-a");
await desk.click("text=I'm ready");
await desk.waitForURL("**/learn/session/**");
const sid = desk.url().split("/").pop();
const tok = await desk.evaluate(async (sid) => (await fetch(`/api/sessions/${sid}/token`, { method: "POST" })).json(), sid);
const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await phone.goto(tok.url);
await phone.waitForSelector("text=Take photo");
await phone.waitForLoadState("networkidle");
await phone.screenshot({ path: S + "/08-phone-start.png" });
await phone.setInputFiles("input[capture]", "tests/handwriting/school-worksheet-p1.jpg");
await phone.screenshot({ path: S + "/09-phone-review.png" });
await phone.click("text=Send 1 page");
await phone.waitForSelector("text=Sent!");
await phone.screenshot({ path: S + "/10-phone-sent.png" });
await desk.reload();
await desk.waitForSelector("text=Page 1:");
await desk.waitForTimeout(4000);
await desk.screenshot({ path: S + "/11-desk-after-phone.png" });
console.log("desk:", (await desk.locator("li", { hasText: "Page 1:" }).innerText()).replace(/\s+/g, " "));
await browser.close();

await page.screenshot({ path: S + "/05-results.png", fullPage: true });
console.log("score:", await page.locator("h1").first().innerText());
await page.goto(base + "/parent");
await page.screenshot({ path: S + "/06-parent.png", fullPage: true });
await page.click("text=waiting to be marked");
await page.waitForSelector("text=Mark this answer:");
const first = page.locator("article", { hasText: "Mark this answer:" }).first();
await first.locator("button", { hasText: /^1$/ }).click();
await page.waitForLoadState("networkidle");
await page.screenshot({ path: S + "/07-review.png" });
await page.goto(base + "/parent");
console.log("latest:", await page.locator("text=Latest worksheet").locator("..").innerText());
await browser.close();

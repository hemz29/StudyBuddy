import { chromium } from "playwright-core";
const S = process.env.S ?? ".", base = process.env.BASE ?? "http://localhost:3100";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto(base + "/profiles");
await page.fill("input[name=nickname]", "Anika");
await page.click("text=Space");
await page.click("text=Start learning");
await page.waitForURL("**/learn");
await page.screenshot({ path: S + "/01-home.png", fullPage: true });
await page.goto(base + "/learn/lesson/nanna-desha");
await page.screenshot({ path: S + "/02-lesson.png" });
await page.goto(base + "/learn/worksheet/term-practice-1");
await page.click("text=I'm ready");
await page.waitForURL("**/learn/session/**");
await page.waitForSelector("text=I'm stuck");
await page.waitForLoadState("networkidle");
const stuck = page.locator("text=I'm stuck").first();
await stuck.click(); await page.locator("text=More help").first().click();
await page.screenshot({ path: S + "/03-worksheet.png" });
await page.waitForLoadState("networkidle");
await page.click("text=Send photos from a phone");
await page.waitForSelector("text=Scan with the phone camera");
await page.setInputFiles("input[type=file]", S + "/hw-2.jpg");
await page.waitForSelector("text=Let's check we read", { timeout: 60000 }).catch(async () => { await page.screenshot({ path: S + "/err.png" }); });
await page.screenshot({ path: S + "/04-upload-check.png", fullPage: true });
await page.waitForTimeout(1500);
await page.screenshot({ path: S + "/04-upload-check.png", fullPage: true });
await page.click("text=Yes, this is what I wrote");
await page.click("text=Mark my work");

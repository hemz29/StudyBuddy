const KN_DIGITS = "೦೧೨೩೪೫೬೭೮೯";
export const toKannadaDigits = (n: number | string) =>
  String(n).replace(/[0-9]/g, (d) => KN_DIGITS[Number(d)]);

export function numberQuestion(n: number) {
  return {
    id: `numbers.${n}`,
    type: "number_name" as const,
    skill: "grammar" as const,
    prompt: toKannadaDigits(n),
    promptEn: String(n),
    answers: NUMBER_NAMES[n],
    model: { kn: NUMBER_NAMES[n][0], en: String(n) },
  };
}
